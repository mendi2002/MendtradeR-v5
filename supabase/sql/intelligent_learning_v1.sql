create table if not exists public.trade_market_context (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  trade_history_id bigint not null unique references public.trade_history(id) on delete cascade,
  asset text not null,
  direction text not null check (direction in ('COMPRA','VENDA')),
  outcome text not null check (outcome in ('win','loss','breakeven')),
  profit numeric not null,
  market_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists trade_market_context_user_created_idx
  on public.trade_market_context(user_id, created_at desc);
create index if not exists trade_market_context_asset_outcome_idx
  on public.trade_market_context(asset, outcome);

alter table public.trade_market_context enable row level security;

drop policy if exists "Users read own trade market context" on public.trade_market_context;
create policy "Users read own trade market context"
  on public.trade_market_context for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users insert own trade market context" on public.trade_market_context;
create policy "Users insert own trade market context"
  on public.trade_market_context for insert to authenticated
  with check ((select auth.uid()) = user_id);

grant select, insert on public.trade_market_context to authenticated;
grant usage, select on sequence public.trade_market_context_id_seq to authenticated;
